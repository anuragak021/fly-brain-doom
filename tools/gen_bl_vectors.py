"""Generate known-answer vectors for the ESP32 feature extractor (doom-nano bl_features.c).

Each case describes a gray image and a sprite id map by a small recipe (so the C test can rebuild
the same arrays), and the expected features computed by game/features.py, the reference the
brain was developed against.

    python -m tools.gen_bl_vectors [--out doom-nano/host/tests/golden/bl_feature_vectors.txt]

Line format:
    CASE <w> <h> <a> <b> <n_rects> [<id> <class> <x0> <x1> <y0> <y1>]... | <f0> .. <f5> <visible> <offset>
Gray pixel = (x * a + y * b) mod 256. Rectangles are painted in order into the id map (x1, y1
inclusive); class 3 and 4 are live monsters, anything else is not.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

from game.features import Label, make_features

MONSTER_CLASSES = (3, 4)
CASES = [
    # name-less: (w, h, a, b, rects)
    (128, 56, 1, 0, []),  # no sprites
    (128, 56, 2, 3, [(7, 3, 10, 29, 10, 40)]),  # monster on the left
    (128, 56, 2, 3, [(9, 3, 90, 119, 12, 44)]),  # monster on the right
    (128, 56, 1, 1, [(5, 4, 56, 71, 8, 40)]),  # hit monster, centred
    (128, 56, 3, 1, [(4, 3, 5, 20, 20, 30), (8, 3, 70, 100, 5, 50)]),  # larger one wins
    (
        128,
        56,
        3,
        1,
        [(4, 3, 5, 20, 20, 29), (8, 3, 100, 115, 20, 29)],
    ),  # tie: lower id wins
    (
        128,
        56,
        1,
        2,
        [(6, 2, 0, 127, 0, 55), (3, 3, 40, 50, 10, 20)],
    ),  # big non-monster ignored
    (
        128,
        56,
        1,
        2,
        [(3, 3, 20, 60, 10, 40), (4, 5, 30, 50, 15, 30)],
    ),  # corpse over a monster
    (128, 56, 5, 7, [(2, 3, 0, 9, 0, 55)]),  # hugging the left edge
    (128, 56, 5, 7, [(2, 3, 118, 127, 0, 55)]),  # hugging the right edge
    (127, 40, 1, 3, [(11, 3, 100, 126, 5, 30)]),  # odd width
    (
        64,
        32,
        4,
        5,
        [(1, 3, 2, 12, 2, 12), (255, 8, 20, 40, 0, 31)],
    ),  # weapon id ignored
]


def build(w: int, h: int, a: int, b: int, rects: list[tuple[int, ...]]):
    """Gray image and id map from a recipe."""
    yy, xx = np.mgrid[0:h, 0:w]
    gray = ((xx * a + yy * b) % 256).astype(np.uint8)
    ids = np.zeros((h, w), dtype=np.uint8)
    for rid, _cls, x0, x1, y0, y1 in rects:
        ids[y0 : y1 + 1, x0 : x1 + 1] = rid
    return gray, ids


def expected(w, h, a, b, rects):
    """Features from game/features.py using the visible bounding boxes of live monsters."""
    gray, ids = build(w, h, a, b, rects)
    cls = {rid: c for rid, c, *_ in rects}
    labels = []
    for rid in sorted(cls):
        if cls[rid] not in MONSTER_CLASSES:
            continue
        ys, xs = np.nonzero(ids == rid)
        if len(xs) == 0:
            continue
        labels.append(
            Label(
                "DoomImp",
                float(xs.min()),
                float(ys.min()),
                float(xs.max() - xs.min() + 1),
                float(ys.max() - ys.min() + 1),
            )
        )
    feat, offset = make_features(gray, labels)
    return feat, offset


def build_lines() -> list[str]:
    """All vector lines, deterministic."""
    out = ["# GENERATED by tools/gen_bl_vectors.py from game/features.py. Do not edit."]
    for w, h, a, b, rects in CASES:
        feat, offset = expected(w, h, a, b, rects)
        recipe = " ".join(" ".join(str(v) for v in r) for r in rects)
        vis = 0 if offset is None else 1
        off = 0.0 if offset is None else offset
        values = " ".join(repr(float(f)) for f in feat)
        out.append(
            f"CASE {w} {h} {a} {b} {len(rects)} {recipe} | {values} {vis} {off!r}"
        )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("doom-nano/host/tests/golden/bl_feature_vectors.txt"),
    )
    args = parser.parse_args(argv)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(build_lines()) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
