"""Generate known-answer vectors for the brain protocol (tests/golden/protocol_vectors.txt).

The file is plain text so C, Python and the ESP32 project can all parse it:

    CRC   <ascii> <crc32 hex>
    Q15   <float> <q15 int>                       sender rounding / clamping
    STEPREQ  <f0> <f1> <f2> <f3> <payload hex>    features -> STEP request payload
    STEPRESP <actions> <cycles> <sl> <sr> <fwd> <back> <payload hex>
    FRAME <name> <type hex> <seq> <payload hex or -> <frame hex>

Regenerate with:  python -m tools.gen_protocol_vectors
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

from game import brain_protocol as bp

Q15_CASES = (0.0, 0.5, 1.0, 0.25, 0.123456, 0.9999, 0.00001, -0.3, 1.5)
STEP_FEATURES = (0.25, 0.75, 0.5, 0.0)
RESP = bp.StepResponse(0x01, 123456, 0.125, 0.25, 0.5, 1.0)
INFO_ARGS = (300, 6, 480000)


def _hex(data: bytes) -> str:
    return data.hex() if data else "-"


def build_lines() -> list[str]:
    """All vector lines, deterministic."""
    out = [
        "# Brain protocol v1 known-answer vectors. GENERATED by tools/gen_protocol_vectors.py."
    ]
    out.append(f"CRC 123456789 {bp.CRC32_CHECK_VALUE:08x}")
    for f in Q15_CASES:
        out.append(f"Q15 {f!r} {bp.feature_to_q15(f)}")
    step_payload = bp.encode_step_request(np.array(STEP_FEATURES, dtype=np.float32))
    out.append(
        "STEPREQ " + " ".join(repr(f) for f in STEP_FEATURES) + f" {step_payload.hex()}"
    )
    resp_payload = bp.encode_step_response(RESP)
    out.append(
        f"STEPRESP {RESP.actions} {RESP.step_cycles} {RESP.steer_left!r} {RESP.steer_right!r} "
        f"{RESP.forward!r} {RESP.backward!r} {resp_payload.hex()}"
    )
    frames = (
        ("ping", bp.MSG_PING, 1, b""),
        ("info", bp.MSG_INFO, 1, bp.encode_info(*INFO_ARGS)),
        ("step", bp.MSG_STEP, 2, step_payload),
        ("step_resp", bp.MSG_STEP_RESP, 2, resp_payload),
        ("reset", bp.MSG_RESET, 3, b""),
        ("reset_resp", bp.MSG_RESET_RESP, 3, b""),
        ("error", bp.MSG_ERROR, 2, bp.encode_error(bp.ERR_BAD_FEATURE, bp.MSG_STEP)),
    )
    for name, mtype, seq, payload in frames:
        frame = bp.encode_frame(mtype, seq, payload)
        out.append(f"FRAME {name} {mtype:02x} {seq} {_hex(payload)} {frame.hex()}")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out", type=Path, default=Path("tests/golden/protocol_vectors.txt")
    )
    args = parser.parse_args(argv)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(build_lines()) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
