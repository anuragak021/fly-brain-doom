"""Export the weight matrix to C (CSR in flash) and write golden test vectors.

Outputs:
  firmware/generated/model_weights.h / .c   const CSR arrays + index lists + constants
  tests/golden/rate_golden.csv               Python controller inputs and outputs

CSR layout (W[post, pre]): row i lists everything flowing INTO neuron i.
  row_ptr[i]..row_ptr[i+1]  -> entries of row i
  col_idx[k]                -> presynaptic neuron of entry k
  values[k]                 -> signed, normalised weight (float32)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

from game import controller as ctl
from model import rate_model as rm

GOLDEN_FRAMES = 60
GOLDEN_SEED = 7
GROUPS = (
    ("INPUT_LEFT", "input", "L", None),
    ("INPUT_RIGHT", "input", "R", None),
    ("STEER_LEFT", "output", "L", "steer"),
    ("STEER_RIGHT", "output", "R", "steer"),
    ("FORWARD", "output", None, "forward"),
    ("BACKWARD", "output", None, "backward"),
)


def to_csr(w: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Dense W[post, pre] -> (row_ptr, col_idx, values)."""
    rows, cols = np.nonzero(w)
    order = np.lexsort((cols, rows))
    rows, cols = rows[order], cols[order]
    row_ptr = np.zeros(w.shape[0] + 1, dtype=np.int64)
    np.add.at(row_ptr, rows + 1, 1)
    return np.cumsum(row_ptr), cols.astype(np.int64), w[rows, cols].astype(np.float32)


def c_array(ctype: str, name: str, values, fmt) -> str:
    """Format a const C array definition."""
    body = ", ".join(fmt(v) for v in values)
    return f"const {ctype} {name}[{len(values)}] = {{{body}}};\n"


def fmt_float(v: float) -> str:
    """C float literal that round-trips float32 (always has '.' or an exponent)."""
    text = f"{float(v):.9g}"
    if not any(c in text for c in ".eEn"):
        text += ".0"
    return f"{text}f"


def header_text(graph: rm.Graph, nnz: int, sizes: dict[str, int]) -> str:
    """Contents of model_weights.h."""
    meta = graph.meta
    lines = [
        "/**",
        " * @file model_weights.h",
        " * @brief GENERATED by model/export_c.py. Do not edit.",
        f" * Source graph : {meta.get('dataset', 'unknown')} on {meta.get('server', 'unknown')}",
        f" * Queried      : {meta.get('queried', 'n/a')}  placeholder={meta.get('placeholder')}",
        (
            f" * Thresholds   : hop1>={meta.get('hop1_min_weight')} hop2>={meta.get('hop2_min_weight')}"
            f" adjacency>={meta.get('adjacency_min_weight')} max_neurons={meta.get('max_neurons')}"
        ),
        f" * Neurons      : {graph.n}",
        (
            f" * Synapses     : {meta.get('n_synapses')} in {meta.get('n_edges')} neuron-pair connections"
            f" ({nnz} with a non-zero signed weight)"
        ),
        " * Convention   : W[post, pre]; CSR row = postsynaptic neuron; sign by presynaptic neuron.",
        " */",
        "#ifndef MODEL_WEIGHTS_H",
        "#define MODEL_WEIGHTS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define MODEL_N_NEURONS {graph.n}U",
        f"#define MODEL_NNZ {nnz}U",
        f"#define MODEL_ALPHA {fmt_float(rm.ALPHA)}",
        f"#define MODEL_SUBSTEPS_PER_FRAME {rm.SUBSTEPS_PER_FRAME}U",
        f"#define MODEL_TONIC_DRIVE {fmt_float(ctl.TONIC_DRIVE)}",
        f"#define MODEL_INPUT_GAIN {fmt_float(ctl.INPUT_GAIN)}",
        f"#define MODEL_LUM_WEIGHT {fmt_float(ctl.LUM_WEIGHT)}",
        "",
    ]
    for name, size in sizes.items():
        lines.append(f"#define MODEL_N_{name} {size}U")
    lines += ["", "extern const uint16_t model_row_ptr[MODEL_N_NEURONS + 1U];"]
    lines += [
        "extern const uint16_t model_col_idx[MODEL_NNZ];",
        "extern const float model_values[MODEL_NNZ];",
    ]
    for name, size in sizes.items():
        lines.append(f"extern const uint16_t model_{name.lower()}[MODEL_N_{name}];")
    lines += ["", "#endif /* MODEL_WEIGHTS_H */", ""]
    return "\n".join(lines)


def source_text(graph: rm.Graph, csr, groups: dict[str, np.ndarray]) -> str:
    """Contents of model_weights.c."""
    row_ptr, col_idx, values = csr
    out = [
        "/** @file model_weights.c  GENERATED by model/export_c.py. Do not edit. */",
        '#include "model_weights.h"',
        "",
    ]
    out.append(c_array("uint16_t", "model_row_ptr", row_ptr, str))
    out.append(c_array("uint16_t", "model_col_idx", col_idx, str))
    out.append(c_array("float", "model_values", values, fmt_float))
    for name, idx in groups.items():
        out.append(c_array("uint16_t", f"model_{name.lower()}", idx, str))
    out.append(
        '_Static_assert(MODEL_N_NEURONS < 65535U, "neuron indices must fit uint16_t");'
    )
    out.append('_Static_assert(MODEL_NNZ < 65535U, "CSR offsets must fit uint16_t");')
    out.append("")
    return "\n".join(out)


def write_golden(graph: rm.Graph, path: Path) -> None:
    """Run the real Python controller on random features and record every output."""
    rng = np.random.default_rng(GOLDEN_SEED)
    controller = ctl.PythonController(graph)
    controller.reset()
    rows = [
        "f_lum_l,f_lum_r,f_enemy_l,f_enemy_r,steer_left,steer_right,forward,backward"
    ]
    for _ in range(GOLDEN_FRAMES):
        feat = rng.random(ctl.N_FEATURES).astype(np.float32)
        out = controller.step(feat)
        vals = [
            *map(float, feat),
            out.steer_left,
            out.steer_right,
            out.forward,
            out.backward,
        ]
        rows.append(",".join(f"{v:.9g}" for v in vals))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(rows) + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--graph", type=Path, default=Path("connectome/data/malecns_v1_0_subgraph.json")
    )
    parser.add_argument("--out-dir", type=Path, default=Path("firmware/generated"))
    parser.add_argument(
        "--golden", type=Path, default=Path("tests/golden/rate_golden.csv")
    )
    args = parser.parse_args(argv)
    graph = rm.load_graph(args.graph)
    csr = to_csr(graph.weights)
    groups = {n: graph.indices(role, side, grp) for n, role, side, grp in GROUPS}
    sizes = {n: len(ix) for n, ix in groups.items()}
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "model_weights.h").write_text(
        header_text(graph, len(csr[2]), sizes)
    )
    (args.out_dir / "model_weights.c").write_text(source_text(graph, csr, groups))
    write_golden(graph, args.golden)
    print(
        f"exported {graph.n} neurons, {len(csr[2])} non-zero weights -> {args.out_dir}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
